// Generates the shared N/E constants from this assembly's [Node] classes and Edges — the
// vocabulary the front end is written against, so a renamed field is a build error rather than
// an empty label. (The workspace injects the same shape above every endpoint script itself.)
//
//   dotnet run --project src/QuranKG.Connector -- --emit-schema src/QuranKG.FrontEnd/src/Schema/N.cs
//
// Re-run after ANY change to Schema.cs or Edges.cs, and commit the result. Never hand-edit it.

using System.Reflection;
using System.Text;
using Curiosity.Library;

namespace QuranKG.Connector;

internal static class SchemaEmitter
{
    public static void Emit(string path)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// Generated by QuranKG.Connector --emit-schema from Schema.cs and Edges.cs. Do not edit.");
        sb.AppendLine();
        sb.AppendLine("namespace QuranKG.FrontEnd.Schema");
        sb.AppendLine("{");
        sb.AppendLine("    public static class N");
        sb.AppendLine("    {");

        foreach (var type in NodeTypes())
        {
            sb.AppendLine($"        public static class {type.Name}");
            sb.AppendLine("        {");
            sb.AppendLine($"            public const string Type = \"{type.Name}\";");
            foreach (var property in type.GetProperties(BindingFlags.Public | BindingFlags.Instance).Where(IsSchemaMember))
                sb.AppendLine($"            public const string {property.Name} = \"{property.Name}\";");
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public static class Groups");
        sb.AppendLine("    {");
        sb.AppendLine($"        public static readonly string[] AllTypes = {{ {string.Join(", ", NodeTypes().Select(t => $"\"{t.Name}\""))} }};");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public static class E");
        sb.AppendLine("    {");
        foreach (var field in typeof(Edges).GetFields().Where(f => f.IsLiteral))
            sb.AppendLine($"        public const string {field.Name} = \"{(string)field.GetRawConstantValue()!}\";");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
        File.WriteAllText(path, sb.ToString());
        Console.WriteLine($"wrote {path}");
    }

    public static IEnumerable<Type> NodeTypes()
        => typeof(SchemaEmitter).Assembly.GetTypes()
            .Where(t => t.GetCustomAttribute<NodeAttribute>() is not null)
            .OrderBy(t => t.Name, StringComparer.Ordinal);

    private static bool IsSchemaMember(PropertyInfo p)
        => p.GetCustomAttribute<KeyAttribute>() is not null || p.GetCustomAttribute<PropertyAttribute>() is not null;
}
