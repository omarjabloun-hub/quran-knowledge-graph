namespace QuranKG.Tools;

/// <summary>
/// Keeps the two declarations of the endpoint DTOs identical. The server's copy
/// (<c>src/QuranKG.Definitions/code/endpoints/qkg/_lib/dto.cs</c>, a workspace script) is the
/// source; the front end's (<c>src/QuranKG.FrontEnd/src/Api/Dto.cs</c>) is generated from it:
/// the <c>QK</c> class up to its "shared reads" helpers, inside the front end's namespace.
///
/// <para>Both ends serialise with the same default resolver, so the property names ARE the wire
/// format: a field added on one side only deserialises to null on the other, silently. With
/// <c>--check</c> nothing is written and a difference fails the run, for CI.</para>
/// </summary>
internal static class SyncDto
{
    private const string SERVER   = "src/QuranKG.Definitions/code/endpoints/qkg/_lib/dto.cs";
    private const string CLIENT   = "src/QuranKG.FrontEnd/src/Api/Dto.cs";
    private const string START    = "public static class QK";
    private const string HELPERS  = "    // --- shared reads";

    public static int Run(string root, bool check)
    {
        var server = File.ReadAllText(Path.Combine(root, SERVER)).Replace("\r\n", "\n");
        var start  = server.IndexOf(START, StringComparison.Ordinal);
        var end    = server.IndexOf(HELPERS, StringComparison.Ordinal);

        if (start < 0 || end < start)
        {
            Console.Error.WriteLine($"{SERVER}: expected '{START}' followed by '{HELPERS.Trim()}'.");
            return 1;
        }

        var body   = server[start..end].TrimEnd() + "\n}\n";
        var client = string.Join("\n",
            "// <auto-generated />",
            "// Generated by `dotnet run --project src/QuranKG.Tools -- sync-dto` from",
            "// " + SERVER + ". Do not edit: change the server's copy and re-run.",
            "",
            "using UID;",
            "",
            "namespace QuranKG.FrontEnd.Api",
            "{",
            Indent(body).TrimEnd(),
            "}",
            "");

        var path    = Path.Combine(root, CLIENT);
        var current = File.Exists(path) ? File.ReadAllText(path).Replace("\r\n", "\n") : null;

        if (current == client)
        {
            Console.WriteLine($"{CLIENT} is in sync.");
            return 0;
        }

        if (check)
        {
            Console.Error.WriteLine($"{CLIENT} differs from {SERVER}: run `dotnet run --project src/QuranKG.Tools -- sync-dto`.");
            return 1;
        }

        File.WriteAllText(path, client);
        Console.WriteLine($"wrote {CLIENT}");
        return 0;
    }

    private static string Indent(string text)
        => string.Join("\n", text.Split('\n').Select(line => line.Length == 0 ? line : "    " + line));
}
