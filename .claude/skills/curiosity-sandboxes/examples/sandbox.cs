// Reference example — this is the OUTPUT of gen.sh + gen_sandbox.py + sandbox-template.cs for the
// template domain (Case / Change / Manual). Definitions path: code/chat-ai-tools/<sandbox uid>.cs.
//
// A sandbox over this application's slice of the graph: bash and Python over a filesystem the code
// below builds, for the open-ended question no fixed tool answers. Generated by
// tools/gen_sandbox.py (tools/sandbox/sandbox-template.cs) from the node types in N.cs - edit the
// generator's settings, not this file. See the curiosity-sandboxes skill.
//
//   /records    one folder per record type, one JSON file per record, rendered only when read
//   /docs       README.md (the layout and the commands), schema.md (live counts), the use case
//   /work       scratch space, kept with the conversation
//   /artifacts  added by the workspace because Artifacts is declared: HTML / markdown the agent
//               writes and `publish`es as a document the reader opens beside the chat
//
// The AI tool's code RETURNS an object implementing ISandbox instead of a class with [Tool]
// methods - that is the whole difference from an ordinary tool. The workspace synthesizes the tool
// surface, supplies the interpreter (bash, jq, awk, sed, python - in process, no host disk, no
// network) and keeps one session per chat AND tool.
//
// Ground-truth types (CaseFinding) are deliberately absent from every mount, from search,
// consult and query, so the assistant can never read the answer key it is scored against.
public class AppSandbox : ISandbox
{
    private static readonly string[] RecordTypes = { "Case", "Category", "Change", "ChangeRevision", "Classification", "Keyword", "Manual", "PartNumber", "Status" };

    // The application's own endpoints the `app` command may call (path relative to the prefix).
    private const string ENDPOINT_PREFIX = "app/";
    private static readonly string[] Endpoints = { "dashboard/summary", "similarity/affected-documents" };

    // A folder lists at most this many records; beyond it the agent is told to use search/query.
    private const int MAX_PER_FOLDER = 5_000;
    // A record file carries at most this many neighbours - enough to join on, small enough to cat.
    private const int MAX_NEIGHBOURS = 150;

    public string FunctionName => "app-sandbox";

    public string Description => "The application's corpus as a filesystem - cases, changes, manuals and their reference data - with bash, jq, awk and python over it, plus search, consult, a read-only graph query engine and the application's own endpoints. Use it for open-ended questions that need counting, joining or comparing many records; read /docs/README.md first.";

    // LAZY for /records: the other mount kinds name every file up front on every script, which
    // for tens of thousands of records costs a full sweep for `pwd`. A lazy mount is asked for one
    // directory and one file at a time, as `ls`, `grep -r` and globs walk into them.
    public SandboxMount[] Mounts => new[]
    {
        SandboxMount.Lazy("/records", "one folder per record type; <type>/<id>.json is one record with its fields and its neighbours, rendered when read; <type>/_index.tsv lists id, label and uid",
            listDirectory: (scope, directory) => Task.FromResult(List(scope, directory)),
            readFile:      (scope, path)      => ReadAsync(scope, path)),

        SandboxMount.Live("/docs", "README.md (start here), schema.md (record types with live counts), use-case.md (what this application is for)", ReadDocs),

        SandboxMount.Scratch("/work", "scratch space for working files - kept for this conversation"),
    };

    // search and consult are the workspace's OWN tools, fenced to RecordTypes: the search runs as
    // the person chatting, and consult reads through the very readers the chat uses - so an id of
    // an excluded (ground-truth) type is refused before the tool is asked.
    public SandboxCommand[] Commands => new[]
    {
        SandboxCommand.Search(RecordTypes),
        SandboxCommand.Consult(RecordTypes),
        SandboxCommand.Create(
            "app",
            "app <endpoint> [json-body]: calls one of this application's own endpoints and prints its JSON - the same numbers and ranked lists the screens show. `app list` prints the endpoints. Pass ids as uids, e.g. app " + (Endpoints.Length > 0 ? Endpoints[0] : "<endpoint>") + " '{}'. Reach for it before recomputing a metric or a ranking by hand.",
            async call =>
            {
                if (call.Arguments.Count == 0 || call.Arguments[0] == "list") return string.Join("\n", Endpoints);

                var endpoint = call.Arguments[0].Trim('/');

                if (!Endpoints.Contains(endpoint)) return call.Fail("unknown endpoint '" + endpoint + "' - `app list` prints the ones available");

                var body = call.Arguments.Count > 1 ? string.Join(" ", call.Arguments.Skip(1)) : (string.IsNullOrWhiteSpace(call.StdinText) ? "{}" : call.StdinText);

                // As the person chatting (no runAsAdmin), and only the READ-ONLY endpoints the
                // generator listed: an endpoint that writes, or the evaluation endpoint that reads
                // the answer key, is not in the list.
                return await call.Scope.RunEndpointAsync<string>(new EndpointUID(ENDPOINT_PREFIX + endpoint), body, cancellationToken: call.CancellationToken) ?? "";
            }),
    };

    // The graph query engine as `query '<IQuery chain>'` - interpreted, read-only, as the user. The
    // allow-list is re-applied after every step, so a traversal cannot walk into an excluded type.
    public SandboxQueryAccess Query => SandboxQueryAccess.For(RecordTypes).WithMaxNodes(200);

    // Declaring any artifact type adds the /artifacts mount and the `publish` command: HTML is shown
    // in a frame with no network, markdown is rendered to a PDF. Leave it empty for a sandbox that
    // only answers questions.
    public ArtifactType[] Artifacts => new[] { ArtifactType.Html, ArtifactType.Pdf };

    // ── /records ─────────────────────────────────────────────────────────────────────────────

    private static SandboxDirectory List(ToolScope scope, string directory)
    {
        directory = directory.Trim('/');

        if (directory.Length == 0) return SandboxDirectory.Of(RecordTypes.Select(t => SandboxEntry.Directory(t)));

        if (!RecordTypes.Contains(directory)) return SandboxDirectory.None;

        var entries = new List<SandboxEntry> { SandboxEntry.File("_index.tsv") };

        foreach (var node in scope.Q().StartAt(directory).Take(MAX_PER_FOLDER).AsEnumerable())
        {
            entries.Add(SandboxEntry.File(FileNameOf(scope, node) + ".json"));
        }

        return SandboxDirectory.Of(entries);
    }

    private static async Task<SandboxFile> ReadAsync(ToolScope scope, string path)
    {
        var parts = path.Trim('/').Split('/');

        if (parts.Length != 2 || !RecordTypes.Contains(parts[0])) return null;

        var type = parts[0];

        if (parts[1] == "_index.tsv")
        {
            var sb = new StringBuilder("#id\tlabel\tuid\n");
            var n  = 0;

            foreach (var node in scope.Q().StartAt(type).AsEnumerable())
            {
                if (++n > MAX_PER_FOLDER) { sb.Append("# truncated at " + MAX_PER_FOLDER + " - use `search` or `query` for the rest\n"); break; }
                sb.Append(FileNameOf(scope, node)).Append('\t').Append(Clean(LabelOf(node))).Append('\t').Append(node.UID).Append('\n');
            }

            return SandboxFile.Text(path, sb.ToString());
        }

        if (!parts[1].EndsWith(".json")) return null;

        var id  = parts[1].Substring(0, parts[1].Length - 5);
        var uid = FindByFileName(scope, type, id);

        if (uid.IsNull()) return null;

        return SandboxFile.Text(path, await RenderAsync(scope, uid));
    }

    private static UID128 FindByFileName(ToolScope scope, string type, string id)
    {
        if (id.Length == 22 && UID128.TryParse(id, out var direct) && scope.Graph.HasNode(direct)) return direct;

        foreach (var node in scope.Q().StartAt(type).AsEnumerable())
        {
            if (FileNameOf(scope, node) == id) return node.UID;
        }

        return default;
    }

    // A record's file is named by its key when the key is a usable file name, else by its uid.
    private static string FileNameOf(ToolScope scope, ReadOnlyNode node)
    {
        if (scope.Graph.TryGetNodeSchemaKey(node.Type, out var keyField))
        {
            string key = null;
            try { key = node.GetString(keyField); } catch (Exception) { } // a non-string key falls back to the uid

            if (!string.IsNullOrWhiteSpace(key) && key.Length <= 120 && key.IndexOfAny(new[] { '/', '\\', '\n', '\t' }) < 0) return key.Trim();
        }

        return node.UID.ToString();
    }

    private static async Task<string> RenderAsync(ToolScope scope, UID128 uid)
    {
        using var ms = new MemoryStream();
        await scope.Q().StartAt(uid).Emit("Record").WriteJsonAsync(ms);

        var neighbours = new List<object>();

        foreach (var n in scope.Q().StartAt(uid).Out().Take(MAX_NEIGHBOURS).AsEnumerable())
        {
            if (n.Type.StartsWith("_") || !RecordTypes.Contains(n.Type)) continue;
            neighbours.Add(new { type = n.Type, id = FileNameOf(scope, n), uid = n.UID.ToString(), label = LabelOf(n) });
        }

        var record = Encoding.UTF8.GetString(ms.ToArray());

        return "{\"Record\":" + record + ",\n\"Neighbours\":" + JsonSerializer.Serialize(neighbours, new JsonSerializerOptions { WriteIndented = true }) + "}\n";
    }

    // ── /docs ────────────────────────────────────────────────────────────────────────────────

    private static Task<IEnumerable<SandboxFile>> ReadDocs(ToolScope scope)
    {
        var schema = new StringBuilder("# Record types\n\n| Type | Records | File name |\n|---|---|---|\n");

        foreach (var type in RecordTypes)
        {
            var count = scope.Q().StartAt(type).Count();
            var key   = scope.Graph.TryGetNodeSchemaKey(type, out var k) ? k : "uid";
            schema.Append("| ").Append(type).Append(" | ").Append(count).Append(" | ").Append(key).Append(" |\n");
        }

        IEnumerable<SandboxFile> files = new[]
        {
            SandboxFile.Text("README.md", Readme),
            SandboxFile.Text("schema.md", schema.ToString()),
            SandboxFile.Text("use-case.md", UseCase),
        };

        return Task.FromResult(files);
    }

    private static string LabelOf(ReadOnlyNode node)
    {
        foreach (var field in new[] { "Title", "Name", "SummaryText", "Description", "Abstract" })
        {
            try
            {
                var v = node.GetString(field);
                if (!string.IsNullOrWhiteSpace(v)) return v.Length > 200 ? v.Substring(0, 200) + "…" : v;
            }
            catch (Exception) { } // the type has no such field
        }

        return "";
    }

    private static string Clean(string s) => (s ?? "").Replace('\t', ' ').Replace('\n', ' ').Replace('\r', ' ');

    private const string Readme = """
# App Sandbox

Change impact analysis: everything in the corpus a proposed change conflicts with, depends on, supersedes or invalidates.

## Layout

- `/records/<Type>/` - one folder per record type (9 types). `_index.tsv` lists every record's id, label
  and uid (grep it first); `<id>.json` is one record - all its fields plus its neighbours - rendered when read.
- `/docs/schema.md` - every record type with its live count and the field its files are named by.
- `/docs/use-case.md` - what this application is for, and the questions it is built to answer.
- `/work/` - scratch space that persists for this conversation.

## Commands

- `search <words...>` - the workspace search, as the person chatting; `--type <Type>` narrows it, `--page 2` pages.
- `consult <uid> [--search <text>]` - one record in full, as the assistant's consult tool reads it.
- `query '<IQuery chain>'` - the graph query engine, read-only (`query --methods` lists what a chain may call),
  e.g. `query 'StartAt("Case").Take(5).Emit()'`.
- `app <endpoint> [json]` - this application's own read-only endpoints (`app list`); the numbers the screens show.
- `publish` - turn an HTML or markdown file under `/artifacts` into a document the reader can open.

## Rules

- Only these record types are here: Case, Category, Change, ChangeRevision, Classification, Keyword, Manual, PartNumber, Status. The evaluation ground truth (CaseFinding) is deliberately not.
- A folder lists at most 5,000 records; use `search` or `query` beyond that.
- Everything is read-only except `/work` and `/artifacts`.
""";

    private const string UseCase = """
# Use case — change impact analysis

An engineer holds one proposed **Change** and has to find, before it is approved, everything in
the corpus it conflicts with, depends on, supersedes or invalidates: other changes, the
**Manual** entries it lands in, and earlier **Case** analyses of similar work.

## The questions it answers

- Which manual entries does this change touch, and through which parts or categories?
- Has anyone already analysed a change like this one, and what did they find?
- What is on my desk, what is urgent, and what could I pick up next?
""";
}

return new AppSandbox();
