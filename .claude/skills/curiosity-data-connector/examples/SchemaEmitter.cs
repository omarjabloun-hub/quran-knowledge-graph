// Reference template: generating the shared N/E constants. See ../SKILL.md §10.
//
// N and E are the shared vocabulary of THREE codebases — this connector, every endpoint, and
// the front end — so all three spell every node type and every field the same way, and a
// rename is a build error rather than an empty label at run time.
//
// The workspace generates the same shape itself, but only from a graph that has already been
// ingested — and it is this connector that decides what that graph contains. So it is
// generated here, by reflection over this assembly's own [Node] classes, and committed.
//
//   dotnet run --project src/App.Connector -- --emit-frontend-schema src/App.FrontEnd/src/Schema/N.cs
//
// Re-run after ANY change to a [Node] class or to Edges.cs. Never hand-edit the output.

using System.Reflection;
using System.Text;
using Curiosity.Library;

namespace App.Connector;

internal static class SchemaEmitter
{
    /// <summary>
    /// Node types the graph owns. They have no [Node] class here to reflect over, so the
    /// fields the application uses are listed explicitly.
    /// </summary>
    private static readonly (string Type, string[] Fields)[] GraphOwnedTypes =
    [
        ("_User",      ["UserName", "Email", "FirstName", "LastName"]),
        ("_FileEntry", ["OriginalName", "ContentType", "Size"]),
    ];

    /// <summary>Types whose records are "documents" — drives the published-file tab and the
    /// default 360 type list, so a new record type joins both by existing. Emitted into GROUPS,
    /// not N: the workspace's own N has no sets, so a set on N invites copying it into an
    /// endpoint, where it does not compile.</summary>
    private static readonly string[] DocumentTypes = ["Case"];

    public static void Emit(string path)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// Generated by App.Connector --emit-frontend-schema. Do not edit.");
        sb.AppendLine();
        sb.AppendLine("namespace App.FrontEnd.Schema");
        sb.AppendLine("{");
        sb.AppendLine("    public static class N");
        sb.AppendLine("    {");

        foreach (var type in NodeTypes())
        {
            sb.AppendLine($"        public static class {type.Name}");
            sb.AppendLine("        {");
            sb.AppendLine($"            public const string Type = \"{type.Name}\";");

            foreach (var property in type.GetProperties(BindingFlags.Public | BindingFlags.Instance))
            {
                if (!IsSchemaMember(property)) continue;
                sb.AppendLine($"            public const string {property.Name} = \"{property.Name}\";");
            }

            sb.AppendLine("        }");
            sb.AppendLine();
        }

        foreach (var (type, fields) in GraphOwnedTypes)
        {
            sb.AppendLine($"        public static class {type}");
            sb.AppendLine("        {");
            sb.AppendLine($"            public const string Type = \"{type}\";");
            foreach (var field in fields) sb.AppendLine($"            public const string {field} = \"{field}\";");
            sb.AppendLine("        }");
            sb.AppendLine();
        }

        sb.AppendLine("    }");
        sb.AppendLine();

        // The SETS matter as much as the constants: a renderer that reads Groups.DocumentTypes or
        // Groups.All360Types picks up a new record type without anyone editing a list by hand.
        // They live in their own class because they are FRONT-END ONLY: server code keeps its
        // own list in the helper library (curiosity-code-endpoints §2).
        sb.AppendLine("    public static class Groups");
        sb.AppendLine("    {");
        sb.AppendLine($"        public static readonly string[] DocumentTypes = {{ {Quoted(DocumentTypes)} }};");
        sb.AppendLine($"        public static readonly string[] All360Types   = {{ {Quoted(NodeTypes().Select(t => t.Name))} }};");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    public static class E");
        sb.AppendLine("    {");
        foreach (var field in typeof(Edges).GetFields().Where(f => f.IsLiteral))
            sb.AppendLine($"        public const string {field.Name} = \"{(string)field.GetRawConstantValue()!}\";");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(path))!);
        File.WriteAllText(path, sb.ToString());

        Console.WriteLine($"wrote {path}");
    }

    private static IEnumerable<Type> NodeTypes()
        => typeof(SchemaEmitter).Assembly
            .GetTypes()
            .Where(t => t.GetCustomAttribute<NodeAttribute>() is object)
            .OrderBy(t => t.Name, StringComparer.Ordinal);

    /// <summary>
    /// [Key] and [Property] only. A [Timestamp] property is NOT a field on the server — it is the
    /// node's own Timestamp — so a constant for it would let a renderer or an endpoint read a
    /// field that is never there (GetString throws server-side, reads null client-side). Read
    /// node.Timestamp instead.
    /// </summary>
    private static bool IsSchemaMember(PropertyInfo property)
        => property.GetCustomAttribute<KeyAttribute>()      is object
        || property.GetCustomAttribute<PropertyAttribute>() is object;

    private static string Quoted(IEnumerable<string> values)
        => string.Join(", ", values.Select(v => $"\"{v}\""));
}
